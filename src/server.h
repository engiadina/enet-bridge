#pragma once
// eNet server functions in the ESP (platform-independent, testable on the host):
//   - answer server keys (SumstatusInfo, immediately) and report them as events
//   - commands/queries one after another with acknowledgement and retry (like the server)
//   - status polling 8 s after each command if the actuator does not report by itself
//   - state table of all channels
//   - local scenes (per key: execute scene or only report)
//   - switches itself off as soon as a telegram from the real server is received
// Time is passed as a parameter (ms); transmission and events go through the Io interface.

#include <stddef.h>
#include <stdint.h>

#include "knxrf.h"

namespace enet {

constexpr size_t kMaxChannels = 48, kMaxActions = 128, kMaxScenes = 32, kMaxKeys = 32, kQueueLen = 64;
// The acknowledgement timeout grows by kAckStepMs per attempt (400, 550, 700 … ms), so short interference does
// not hit all attempts (the eNet Server only tries 3× at 400 ms intervals)
constexpr uint32_t kAckTimeoutMs = 400, kAckStepMs = 150, kPollDelayMs = 8000;
constexpr uint8_t kTries = 5;
constexpr uint32_t kRealServerReportMs = 60000;  // report a real server at most once per minute
// Channel busy (LBT): retry sending after kBusyRetryMs without using up an attempt, at most kBusyRetries×
constexpr uint32_t kBusyRetryMs = 20;
constexpr uint8_t kBusyRetries = 20;
// Group telegrams (scene recall) are not acknowledged: send kGroupRepeats× with a gap of kGroupGapMs
constexpr uint8_t kGroupRepeats = 3;
constexpr uint32_t kGroupGapMs = 80;
constexpr uint16_t kGoStatus = 20, kGoStatusValue = 21, kGoSumstatusInfo = 22;
// Blind CT_1F03 (catalog, untested): GO2 up/down (1.008), GO3 stop/step (1.007), GO4 stop (1.017),
// GO5 position (5.001), GO6 slat (5.001), GO10 movement info (2 bits: 0 stopped at top, 1 stopped at bottom,
// 2 moving up, 3 moving down), GO11 SumstatusInfo, GO12 current position, GO13 current slat. Position 0 % = top.
constexpr uint16_t kGoBlindMove = 2, kGoBlindStep = 3, kGoBlindStop = 4, kGoBlindPos = 5, kGoBlindSlat = 6,
                   kGoBlindInfo = 10, kGoBlindSumstatus = 11, kGoBlindPosNow = 12, kGoBlindSlatNow = 13;
constexpr uint8_t kSpanLight = 26, kSpanBlind = 19;  // handles per channel (offset .. offset + span - 1)
// The GO numbers above are those of the default channel types CT_1F01/CT_1F02 (light) and CT_1F03 (blind).
// Installations switch channels to variants with other numbers (e.g. CT_1F05: status GO 17); since format version 4
// the host sends the GO numbers per channel (Channel::go, slots below; 0 = default above).
enum GoSlot : uint8_t {
  kSlotOn = 0, kSlotValue = 1, kSlotStatus = 2, kSlotStatusValue = 3, kSlotSumInfo = 4,  // light (SOO ASC IOO ADV SSGI)
  kSlotMove = 0, kSlotStep = 1, kSlotStop = 2, kSlotPos = 3, kSlotSlat = 4,  // blind (MUD SSUD STOP SAPBP SAPSP)
  kSlotInfo = 5, kSlotSum = 6, kSlotPosNow = 7, kSlotSlatNow = 8,            // blind (IMUDS SSGI CAPBP CAPSP)
  kSlotSpan = 9,                                                             // handles per channel
  kGoSlots = 10
};
// Blind: movements take longer than a light – poll several times after a command (ms after the command)
constexpr uint32_t kBlindPollMs[] = {8000, 25000, 60000, 120000};
constexpr uint8_t kBlindPolls = sizeof(kBlindPollMs) / sizeof(kBlindPollMs[0]);

struct Channel {
  uint16_t ia;
  uint8_t sn[6];
  uint8_t offset;  // channel offset (handle = offset + GO)
  bool dimmer;
  uint8_t gaBase;  // own GAs = gaBase * 256 + GO (changes with every factory reset)
  uint8_t ch;      // channel number as in the export (1, 2, ...) – addressing by the host
  uint8_t obj;     // channel object (link table, parameters)
  bool blind;      // blind (flags bit 1) – at the end so that existing initializations remain valid
  uint8_t go[kGoSlots];  // GO numbers per GoSlot from the channel type (format 4); 0 = default (goOf)
};
// GO number of a slot: from the configuration, otherwise the default of the channel kind
uint8_t goOf(const Channel& ch, GoSlot slot);
struct Action {
  uint16_t ia, handle;  // ia = 0: group telegram under server SN to GA = handle (scene recall)
  uint8_t len;
  uint8_t value[4];
};
struct Scene {
  uint8_t first, count;  // range in Config::actions
};
struct Key {
  uint8_t sn[6];  // transmitter
  uint16_t ga;    // GA of the server key (only the lower byte = offset + 6 is compared)
  int8_t scene;   // < 0: report only
};

struct Config {
  uint8_t domain[6] = {};
  uint8_t serverSn[6] = {};
  uint16_t serverIa = knxrf::kServerIA;
  Channel channels[kMaxChannels];
  Action actions[kMaxActions];
  Scene scenes[kMaxScenes];
  Key keys[kMaxKeys];
  uint8_t nChannels = 0, nActions = 0, nScenes = 0, nKeys = 0;
};

// Binary format version 4 (generated by esp_config.py / tools/server_cfg.py), all numbers big endian:
//   'E' 0x04 | domain(6) | server SN(6) | server IA(2) | nCh nAct nScenes nKeys (1 each)
//   channels: IA(2) SN(6) channel no.(1) offset(1) object(1) flags(1, bit0 dimmer, bit1 blind) GA base(1)
//             GO numbers(kGoSlots, GoSlot order; 0 = default) – missing in version 3, which is still accepted
//   actions: IA(2) handle(2) length(1) value(length, max 4); IA 0 = group telegram to GA = handle
//   scenes: first action(1) count(1)
//   keys: SN(6) GA(2) scene(1, signed)
//   CRC16 (knxrf::crc16 over everything before it)
bool parseConfig(const uint8_t* blob, size_t len, Config& c);
size_t serializeConfig(const Config& c, uint8_t* out, size_t cap);

struct ChannelState {
  bool known = false, on = false;
  uint8_t percent = 0;  // blind: position (0 % = top)
  uint8_t slat = 0;     // blind: slat
  uint8_t move = 0xFF;  // blind: movement info GO10 (0xFF unknown)
  bool pollPending = false;
  uint32_t pollAt = 0, cmdAt = 0;
  uint8_t pollStage = 0;  // blind: next poll from kBlindPollMs
};

enum class Source : uint8_t { STATUS_MSG, POLL, CACHE };
// GO_*: group object via FuncProp (switching, status); PROP_*: A_PropertyValue (parameters, load state …);
// NP_WRITE: A_NetworkParameter_Write P2P without response (considered done after sending);
// FP_CMD/FP_READ: FuncProp on any object/PID (link table); GROUP_WRITE: under server SN to a GA
// (scene recall), without acknowledgement, sent kGroupRepeats×
enum class JobKind : uint8_t { GO_SET, GO_READ, PROP_READ, PROP_WRITE, NP_WRITE, FP_CMD, FP_READ, GROUP_WRITE };
constexpr size_t kMaxJobData = 16;
enum class Origin : uint8_t { HOST, SCENE, POLL };

// SERVER: SumstatusGet to the server SN (server key); DIRECT: SumstatusGet to an actuator (linked
// key/rocker); VALUE: bare key value of an unassigned rocker (2 bytes), also brightness of the sun sensor
// (DPT 9); VALUE1: 1-byte group value under transmitter SN (sun sensor: scene number in bits 5-0, since 0.8.9).
// VALUE4: 4-byte group value under transmitter SN (energy sensor: power DPT 14, energy DPT 13; since 0.8.21).
enum class KeyKind : uint8_t { SERVER, DIRECT, VALUE, VALUE1, VALUE4 };

struct KeyEvent {
  const uint8_t* senderSn;
  uint16_t ga;
  KeyKind kind;
  uint16_t cmd;            // key value (for VALUE the 2 data bytes, for VALUE1 the data byte)
  knxrf::SumstatusGet sg;  // SERVER/DIRECT only
  int keyIndex;            // -1: not configured (SERVER only)
  bool press, answered, sceneStarted;
  uint8_t rfInfo;          // RF info of the telegram (bit 1: battery OK)
  uint32_t value32;        // VALUE4 only
};

class Io {
 public:
  virtual ~Io() {}
  // Frame without CRCs; the caller of the radio link sets the LFN.
  virtual bool transmit(const uint8_t* frame, size_t len) = 0;
  virtual void onKey(const KeyEvent& e) = 0;
  virtual void onState(const Channel& ch, const ChannelState& st, Source src) = 0;
  // id: job number of the host (0 = internal), rc: return code of the device (0 OK, -1 no acknowledgement)
  virtual void onResult(uint32_t id, uint16_t ia, uint16_t handle, bool isRead, Origin o, bool ok, int rc,
                        uint8_t tries, const uint8_t* val, size_t len) = 0;
  // Result of PROP_*/NP_WRITE/FP_*/GROUP_WRITE (rc: 0 OK, -1 no response, otherwise code of the device;
  // PROP: 1 = rejects). GROUP_WRITE: ia = 0, start = GA.
  virtual void onPropResult(uint32_t id, uint16_t ia, JobKind kind, uint8_t obj, uint8_t pid, uint16_t start,
                            bool ok, int rc, uint8_t tries, const uint8_t* val, size_t len) {}
  virtual void onSceneDone(uint32_t id, uint8_t scene, uint8_t failed) = 0;
  virtual void onRealServer() = 0;
};

class Server {
 public:
  explicit Server(Io& io) : io_(io) {}

  void setConfig(const Config& c);
  const Config& config() const { return cfg_; }
  void setEnabled(bool on) { enabled_ = on; }
  bool enabled() const { return enabled_; }

  void onFrame(const knxrf::Telegram& t, uint32_t now);
  void tick(uint32_t now);

  bool queueSet(uint16_t ia, uint16_t handle, const uint8_t* v, uint8_t len, Origin o = Origin::HOST,
                uint32_t id = 0);
  bool queueRead(uint16_t ia, uint16_t handle, Origin o = Origin::HOST, uint32_t id = 0);
  // Read a property (data = nullptr) or write it; count = number of elements (1..15)
  bool queueProp(JobKind kind, uint16_t ia, uint8_t obj, uint8_t pid, uint16_t start, uint8_t count,
                 const uint8_t* data, uint8_t len, uint32_t id);
  bool queueNpWrite(uint16_t ia, const uint8_t* data, uint8_t len, uint32_t id);
  // FuncProp to object/PID with raw data (kind = FP_CMD or FP_READ)
  bool queueFuncProp(JobKind kind, uint16_t ia, uint8_t obj, uint8_t pid, const uint8_t* data, uint8_t len,
                     uint32_t id);
  bool queueGroupWrite(uint16_t ga, const uint8_t* data, uint8_t len, uint32_t id);
  bool runScene(uint8_t idx, uint32_t id = 0);
  size_t queueLength() const { return qCount_ + (busy_ ? 1 : 0); }

  const ChannelState& state(size_t i) const { return st_[i]; }
  int channelIndex(uint16_t ia, uint16_t handle) const;  // -1: unknown
  int channelIndexByCh(uint16_t ia, uint8_t ch) const;   // -1: unknown
  bool busy() const { return busy_; }

 private:
  struct Job {
    JobKind kind;
    uint16_t ia, handle;
    uint8_t obj, pid, count;  // PROP_*
    uint16_t start;
    uint8_t len;
    uint8_t value[kMaxJobData];
    bool read;  // GO_READ
    Origin origin;
    uint32_t id;
    int8_t scene;  // >= 0: belongs to this scene
    bool lastOfScene;
  };
  bool push(const Job& j);
  void startJob(uint32_t now);
  void sendJob(uint32_t now);
  void finishJob(bool ok, int rc, const uint8_t* val, size_t len, uint32_t now);
  void sceneStep(bool ok);
  void updateState(int ci, bool setOn, bool on, bool setPercent, uint8_t percent, Source src);
  void updateBlind(int ci, int percent, int slat, int move, Source src);  // -1: unchanged
  void schedulePoll(int ci, uint32_t now);

  Io& io_;
  Config cfg_;
  ChannelState st_[kMaxChannels];
  uint16_t lastSeq_[kMaxKeys] = {};
  bool lastSeqValid_[kMaxKeys] = {};
  uint16_t lastAnySeq_[kMaxKeys] = {};  // last seq of the key at all (press or release)
  bool lastAnyValid_[kMaxKeys] = {};
  uint8_t sceneFailed_[kMaxScenes] = {};
  bool enabled_ = false;
  bool realServerSeen_ = false;
  uint32_t realServerAt_ = 0;  // last "real server" report

  Job q_[kQueueLen];
  size_t qHead_ = 0, qCount_ = 0;
  bool busy_ = false;
  Job cur_{};
  uint8_t tries_ = 0, busyRetries_ = 0;
  bool txPending_ = false;  // last transmit attempt not sent because the channel was busy
  uint32_t deadline_ = 0;
};

}  // namespace enet
